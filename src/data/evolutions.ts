const EVOLUTION_PREV: Record<string, string> = {};
for (const [fromId, targets] of Object.entries(EVOLUTION_NEXT)) {
  for (const toId of targets) {
    EVOLUTION_PREV[toId] = fromId;
  }
}

export function getEvolutionTargets(speciesId: string): string[] {
  return EVOLUTION_NEXT[speciesId] ?? [];
}

export function getBaseFamilyId(speciesId: string): string {
  let cur = speciesId;
  const seen = new Set<string>();
  while (EVOLUTION_PREV[cur] && !seen.has(cur)) {
    seen.add(cur);
    cur = EVOLUTION_PREV[cur];
  }
  return cur;
}
