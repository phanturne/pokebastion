export function getSpeciesTypes(
  speciesId: string,
): readonly PokemonElementType[] {
  return SPECIES_ELEMENT_TYPES[speciesId] ?? ['Normal'];
}

export function getSpeciesAttackType(speciesId: string): PokemonElementType {
  return ATTACK_TYPE_OVERRIDES[speciesId] ?? getSpeciesTypes(speciesId)[0];
}

export function computeTypeEffectiveness(
  attackType: PokemonElementType,
  defenderTypes: readonly PokemonElementType[],
): { multiplier: number; tier: EffectivenessTier } {
  let raw = 1;
  for (const defType of defenderTypes) {
    raw *= TYPE_CHART[attackType]?.[defType] ?? 1;
  }

  if (raw === 0 || raw <= 0.25) {
    return { multiplier: 0.35, tier: 'very_ineffective' };
  }
  if (raw >= 4) {
    return { multiplier: 2.0, tier: 'extremely' };
  }
  if (raw >= 2) {
    return { multiplier: 1.5, tier: 'super' };
  }
  if (raw <= 0.5) {
    return { multiplier: 0.5, tier: 'not_very' };
  }
  return { multiplier: 1.0, tier: 'neutral' };
}
